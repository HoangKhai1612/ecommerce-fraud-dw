# Phase 20 — Initialize PostgreSQL objects for Metabase.
#
# Creates, idempotently, on the Windows PostgreSQL instance (localhost:5432):
#   1. Login role  metabase_ro  (read-only access to the Data Warehouse)
#   2. Database    metabase_db  (Metabase application metadata store)
#   3. Grants: CONNECT on ecommerce_fraud_dw, USAGE on marts,
#      SELECT on all marts tables (+ default privileges for future tables)
#
# Secrets (metabase_ro password, Metabase admin credentials) are generated
# only if absent and appended to .env (gitignored). Nothing is printed.
#
# Run from the project root:
#   .\metabase\init_database.ps1

$ErrorActionPreference = "Stop"

$ProjectRoot = Split-Path -Parent $PSScriptRoot
$EnvPath = Join-Path $ProjectRoot ".env"
$Psql = "C:\Program Files\PostgreSQL\18\bin\psql.exe"

# ---------------------------------------------------------------- .env ----
$EnvVars = @{}
Get-Content $EnvPath | ForEach-Object {
    if ($_ -match "^([^#=]+)=(.*)$") {
        $EnvVars[$matches[1].Trim()] = $matches[2].Trim()
    }
}

function New-StrongPassword([int]$Length = 24) {
    # alphanumeric only: safe for connection strings, JSON, SQL, URLs
    $chars = "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    -join (1..$Length | ForEach-Object { $chars[(Get-Random -Maximum $chars.Length)] })
}

$NewVars = @{}
if (-not $EnvVars.ContainsKey("METABASE_RO_PASSWORD")) {
    $NewVars["METABASE_RO_PASSWORD"] = New-StrongPassword
}
if (-not $EnvVars.ContainsKey("METABASE_ADMIN_EMAIL")) {
    $NewVars["METABASE_ADMIN_EMAIL"] = "admin@frauddw.local"
}
if (-not $EnvVars.ContainsKey("METABASE_ADMIN_PASSWORD")) {
    $NewVars["METABASE_ADMIN_PASSWORD"] = New-StrongPassword
}

# ------------------------------------------------- existing objects check --
$env:PGPASSWORD = $EnvVars["POSTGRES_PASSWORD"]

function Invoke-PsqlSql {
    # Runs a SQL string via psql stdin; throws on any error.
    param([string]$Sql, [string]$Database = "postgres")
    $Sql | & $Psql -h localhost -U postgres -d $Database -v ON_ERROR_STOP=1 | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "psql failed (exit $LASTEXITCODE)"
    }
}

$RoleExists = & $Psql -h localhost -U postgres -d postgres -Atc `
    "SELECT 1 FROM pg_roles WHERE rolname = 'metabase_ro';"
$DbExists   = & $Psql -h localhost -U postgres -d postgres -Atc `
    "SELECT 1 FROM pg_database WHERE datname = 'metabase_db';"

# ------------------------------------------------------------- create ----
if ($RoleExists -ne "1") {
    $roPassword = if ($NewVars.ContainsKey("METABASE_RO_PASSWORD")) {
        $NewVars["METABASE_RO_PASSWORD"]
    } else {
        $EnvVars["METABASE_RO_PASSWORD"]
    }
    Invoke-PsqlSql "CREATE ROLE metabase_ro LOGIN PASSWORD '$roPassword';"
    Write-Host "Created role metabase_ro"
} else {
    Write-Host "Role metabase_ro already exists (unchanged)"
}

if ($DbExists -ne "1") {
    & $Psql -h localhost -U postgres -d postgres -c "CREATE DATABASE metabase_db;" | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "CREATE DATABASE metabase_db failed" }
    Write-Host "Created database metabase_db"
} else {
    Write-Host "Database metabase_db already exists (unchanged)"
}

# --------------------------------------------------------------- grants ----
$Grants = @"
GRANT CONNECT ON DATABASE ecommerce_fraud_dw TO metabase_ro;
GRANT USAGE ON SCHEMA marts TO metabase_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA marts TO metabase_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA marts GRANT SELECT ON TABLES TO metabase_ro;
"@
Invoke-PsqlSql $Grants "ecommerce_fraud_dw"
Write-Host "Granted CONNECT/USAGE/SELECT to metabase_ro on marts"

# ---------------------------------------------------------------- .env ----
if ($NewVars.Count -gt 0) {
    $lines = Get-Content $EnvPath
    $updated = @()
    foreach ($line in $lines) {
        $key = if ($line -match "^([^#=]+)=") { $matches[1].Trim() } else { $null }
        if ($key -and $NewVars.ContainsKey($key)) {
            $updated += "$key=$($NewVars[$key])"
            $NewVars.Remove($key)
        } else {
            $updated += $line
        }
    }
    if ($NewVars.Count -gt 0) {
        $updated += ""
        $updated += "# Metabase (Phase 20) - generated by metabase/init_database.ps1"
        foreach ($k in $NewVars.Keys) { $updated += "$k=$($NewVars[$k])" }
    }
    Set-Content -LiteralPath $EnvPath -Value $updated
    Write-Host "Appended new Metabase settings to .env"
} else {
    Write-Host ".env already contains all Metabase settings"
}

# ------------------------------------------------------------ verify ------
# Use the metabase_ro password (from .env or newly generated) for the test.
$RoPassword = if ($EnvVars.ContainsKey("METABASE_RO_PASSWORD")) {
    $EnvVars["METABASE_RO_PASSWORD"]
} else {
    $NewVars["METABASE_RO_PASSWORD"]
}
$env:PGPASSWORD = $RoPassword
$RoTest = & $Psql -h localhost -U metabase_ro -d ecommerce_fraud_dw -Atc `
    "SELECT COUNT(*) FROM marts.predictions;" 2>&1
if ($LASTEXITCODE -eq 0) {
    Write-Host "metabase_ro read-only login verified (marts.predictions rows: $RoTest)"
} else {
    Write-Error "metabase_ro login failed: $RoTest"
}
